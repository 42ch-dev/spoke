#!/usr/bin/env node
/**
 * Golden vector sync gate — SSOT → registered copies.
 *
 * Every cross-language golden vector has exactly one source of truth under
 * `crates/spoke-connect/tests/fixtures/` (the Rust crate is the historical
 * libp2p capture authority):
 *
 *   golden-hello.json           (SSOT, hello + dial-binding responder)
 *   golden-envelope-auth.json   (SSOT, envelope-auth session /
 *                                invoke-request / invoke-response families)
 *
 * Each SSOT is validated structurally below, and every registered copy must
 * be byte-identical to its whole SSOT file.
 *
 * - golden-hello.json also carries a **responder vector** (`responder`
 *   block): the same key pair / manifest signed over the 5-field object
 *   incl. `peer_nonce` = the initiator golden nonce, with its own pinned
 *   JCS bytes and signature. The `manifest_json` convenience field (stable
 *   host JSON string for FFI smokes) is derived from `manifest` with the
 *   canonical serde field order, never hand-maintained separately.
 * - golden-envelope-auth.json carries, per envelope family (`session`,
 *   `invoke_request`, `invoke_response`), ≥1 **positive** vector (a full
 *   wire envelope with pinned JCS bytes + signature that must verify) and
 *   ≥1 **negative** vector (a tampered / stripped wire envelope with the
 *   pinned rejection kind). TS and Rust consumers verify the positives and
 *   reproduce the pinned signatures by re-signing the same inputs — the
 *   TS↔Rust canonical-bytes parity proof.
 *
 * Pinned outputs in the SSOTs are transcribed from committed libp2p-captured
 * / core-generated constants — never regenerated by running the code under
 * test.
 *
 * Usage:
 *   node tooling/connect/golden-vector-sync.mjs          # verify (exit 0 iff clean)
 *   node tooling/connect/golden-vector-sync.mjs --write  # refresh copies (+ derived fields)
 *
 * CI runs verify; `--write` is a maintainer refresh only.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const writeMode = process.argv.includes("--write");

const HEX64 = /^[0-9a-f]{64}$/;
const HEX528 = /^[0-9a-f]{528}$/;
const HEX614 = /^[0-9a-f]{614}$/;
const HEX_EVEN = /^[0-9a-f]+$/;
const B64U86 = /^[A-Za-z0-9_-]{86}$/;
const BASE58 = /^[1-9A-HJ-NP-Za-km-z]+$/;
const AUTH_KINDS = new Set([
  "envelope_auth_missing",
  "envelope_auth_invalid",
  "envelope_auth_session_unbound",
]);

/**
 * Re-serialize `manifest` with the canonical serde field order of the
 * generated `HostCapabilityManifest` (alphabetical: capabilities,
 * extensions, host_id, namespaces, roles, schema_version).
 */
function canonicalManifestJson(manifest) {
  return JSON.stringify({
    capabilities: manifest.capabilities,
    extensions: manifest.extensions,
    host_id: manifest.host_id,
    namespaces: manifest.namespaces,
    roles: manifest.roles,
    schema_version: manifest.schema_version,
  });
}

/**
 * Order-insensitive deep equality (JSON values only). Key order must never
 * matter — the SSOT `manifest` object and the parsed `manifest_json` may
 * legitimately order keys differently.
 */
function deepEqual(a, b) {
  if (a === b) return true;
  if (typeof a !== typeof b) return false;
  if (Array.isArray(a)) {
    return (
      Array.isArray(b) &&
      a.length === b.length &&
      a.every((value, i) => deepEqual(value, b[i]))
    );
  }
  if (typeof a === "object" && a !== null && b !== null) {
    const aKeys = Object.keys(a);
    const bKeys = Object.keys(b);
    return (
      aKeys.length === bKeys.length &&
      aKeys.every((key) => deepEqual(a[key], b[key]))
    );
  }
  return false;
}

/** Structural checks on the hello SSOT; appends problems (empty = ok). */
function checkHelloSsot(ssot, problems) {
  if (ssot.version !== 1) {
    problems.push(`version: expected 1, got ${JSON.stringify(ssot.version)}`);
  }
  if (typeof ssot.seed_hex !== "string" || !HEX64.test(ssot.seed_hex)) {
    problems.push("seed_hex: expected 64 lowercase hex chars");
  }
  if (typeof ssot.pubkey_hex !== "string" || !HEX64.test(ssot.pubkey_hex)) {
    problems.push("pubkey_hex: expected 64 lowercase hex chars");
  }
  if (typeof ssot.jcs_hex !== "string" || !HEX528.test(ssot.jcs_hex)) {
    problems.push("jcs_hex: expected 528 lowercase hex chars (264 bytes)");
  }
  if (typeof ssot.signature_b64u !== "string" || !B64U86.test(ssot.signature_b64u)) {
    problems.push("signature_b64u: expected 86 base64url no-padding chars (64 bytes)");
  }
  if (typeof ssot.nonce !== "string" || ssot.nonce.length < 16) {
    problems.push("nonce: expected a string of at least 16 chars (wire floor)");
  }
  if (typeof ssot.peer_id !== "string" || !BASE58.test(ssot.peer_id)) {
    problems.push("peer_id: expected a base58btc string");
  }

  const manifest = ssot.manifest;
  if (typeof manifest !== "object" || manifest === null || Array.isArray(manifest)) {
    problems.push("manifest: expected an object");
    return;
  }
  if (Object.hasOwn(manifest, "authority")) {
    problems.push("manifest.authority: must be omitted (never null)");
  }
  if (!Array.isArray(manifest.namespaces)) {
    problems.push("manifest.namespaces: expected an array");
  }
  for (const key of ["capabilities", "roles"]) {
    const value = manifest[key];
    if (
      !Array.isArray(value) ||
      !value.every((v) => typeof v === "string")
    ) {
      problems.push(`manifest.${key}: expected an array of strings`);
    }
  }
  if (manifest.host_id !== "golden-host") {
    problems.push(`manifest.host_id: expected "golden-host", got ${JSON.stringify(manifest.host_id)}`);
  }
  if (manifest.schema_version !== 1) {
    problems.push(`manifest.schema_version: expected 1, got ${JSON.stringify(manifest.schema_version)}`);
  }

  // manifest_json must be the canonical serde serialization of manifest —
  // FFI smokes pass it verbatim to sign_hello_ed25519, so byte parity with
  // the pinned JCS/signature requires the exact field order.
  if (typeof ssot.manifest_json !== "string") {
    problems.push("manifest_json: expected a string");
    return;
  }
  let roundTrip;
  try {
    roundTrip = JSON.parse(ssot.manifest_json);
  } catch {
    problems.push("manifest_json: not valid JSON");
    return;
  }
  if (!deepEqual(roundTrip, manifest)) {
    problems.push("manifest_json: does not round-trip to manifest");
  }
  if (ssot.manifest_json !== canonicalManifestJson(manifest)) {
    problems.push("manifest_json: not the canonical serde serialization of manifest");
  }

  // Responder golden (5-field signed object, dial binding): a NEW additional
  // vector pinned when the dial-binding mechanism landed — it does not change
  // the initiator golden above. The responder signs over the SAME key pair /
  // manifest with `peer_nonce` = the initiator golden nonce; because
  // `peer_nonce` is INSIDE the signed object, the responder JCS bytes and
  // signature must differ from the 4-field initiator vector (which pins the
  // two vectors to distinct roles, not just distinct nonces).
  const responder = ssot.responder;
  if (typeof responder !== "object" || responder === null || Array.isArray(responder)) {
    problems.push("responder: expected an object");
    return;
  }
  if (typeof responder.nonce !== "string" || responder.nonce.length < 16) {
    problems.push("responder.nonce: expected a string of at least 16 chars (wire floor)");
  }
  if (typeof responder.peer_nonce !== "string" || responder.peer_nonce !== ssot.nonce) {
    problems.push("responder.peer_nonce: expected the initiator golden nonce");
  }
  if (typeof responder.jcs_hex !== "string" || !HEX614.test(responder.jcs_hex)) {
    problems.push("responder.jcs_hex: expected 614 lowercase hex chars (307 bytes)");
  } else if (responder.jcs_hex === ssot.jcs_hex) {
    problems.push("responder.jcs_hex: must differ from the initiator jcs_hex (peer_nonce is inside the signed object)");
  }
  if (typeof responder.signature_b64u !== "string" || !B64U86.test(responder.signature_b64u)) {
    problems.push("responder.signature_b64u: expected 86 base64url no-padding chars (64 bytes)");
  } else if (responder.signature_b64u === ssot.signature_b64u) {
    problems.push("responder.signature_b64u: must differ from the initiator signature");
  }
}

/** Structural checks on the envelope-auth SSOT; appends problems (empty = ok). */
function checkEnvelopeAuthSsot(ssot, problems) {
  if (ssot.version !== 1) {
    problems.push(`version: expected 1, got ${JSON.stringify(ssot.version)}`);
  }
  if (typeof ssot.seed_hex !== "string" || !HEX64.test(ssot.seed_hex)) {
    problems.push("seed_hex: expected 64 lowercase hex chars");
  }
  if (typeof ssot.pubkey_hex !== "string" || !HEX64.test(ssot.pubkey_hex)) {
    problems.push("pubkey_hex: expected 64 lowercase hex chars");
  }
  if (typeof ssot.peer_id !== "string" || !BASE58.test(ssot.peer_id)) {
    problems.push("peer_id: expected a base58btc string");
  }

  for (const family of ["session", "invoke_request", "invoke_response"]) {
    const block = ssot[family];
    if (typeof block !== "object" || block === null || Array.isArray(block)) {
      problems.push(`${family}: expected an object`);
      continue;
    }
    const positives = block.positive;
    const negatives = block.negative;
    if (!Array.isArray(positives) || positives.length < 1) {
      problems.push(`${family}.positive: expected an array of ≥1 vector`);
    }
    if (!Array.isArray(negatives) || negatives.length < 1) {
      problems.push(`${family}.negative: expected an array of ≥1 vector`);
    }
    for (const [i, vector] of (positives ?? []).entries()) {
      if (typeof vector?.envelope_json !== "string") {
        problems.push(`${family}.positive[${i}].envelope_json: expected a string`);
        continue;
      }
      let wire;
      try {
        wire = JSON.parse(vector.envelope_json);
      } catch {
        problems.push(`${family}.positive[${i}].envelope_json: not valid JSON`);
      }
      if (typeof vector.jcs_hex !== "string" || !HEX_EVEN.test(vector.jcs_hex)) {
        problems.push(`${family}.positive[${i}].jcs_hex: expected even-length lowercase hex`);
      }
      if (typeof vector.signature_b64u !== "string" || !B64U86.test(vector.signature_b64u)) {
        problems.push(`${family}.positive[${i}].signature_b64u: expected 86 base64url no-padding chars (64 bytes)`);
      } else if (wire && wire.signature !== vector.signature_b64u) {
        problems.push(`${family}.positive[${i}]: envelope signature differs from the pinned signature_b64u`);
      }
    }
    const positiveTexts = (positives ?? [])
      .map((vector) => vector?.envelope_json)
      .filter((s) => typeof s === "string");
    for (const [i, vector] of (negatives ?? []).entries()) {
      if (typeof vector?.envelope_json !== "string") {
        problems.push(`${family}.negative[${i}].envelope_json: expected a string`);
        continue;
      }
      try {
        JSON.parse(vector.envelope_json);
      } catch {
        problems.push(`${family}.negative[${i}].envelope_json: not valid JSON`);
      }
      if (typeof vector.kind !== "string" || !AUTH_KINDS.has(vector.kind)) {
        problems.push(
          `${family}.negative[${i}].kind: expected one of ${[...AUTH_KINDS].join(", ")}`,
        );
      }
      if (positiveTexts.includes(vector.envelope_json)) {
        problems.push(`${family}.negative[${i}]: must differ from every positive envelope_json`);
      }
    }
  }

  // The golden host (the fixture `peer_id`) is the session initiator — the
  // pinned session vector signs the golden host's own snapshot.
  const sessionPositive = ssot.session?.positive?.[0];
  if (sessionPositive) {
    try {
      const wire = JSON.parse(sessionPositive.envelope_json);
      if (wire.initiator_peer_id !== ssot.peer_id) {
        problems.push("session.positive[0]: initiator_peer_id must equal the fixture peer_id (the golden host signs its own snapshot)");
      }
    } catch {
      // envelope_json parse failure is already reported above.
    }
  }
}

/** One registered golden vector: SSOT path, copies, checker, optional refresh. */
const VECTORS = [
  {
    name: "hello",
    ssotPath: join(REPO_ROOT, "crates/spoke-connect/tests/fixtures/golden-hello.json"),
    copies: [
      "packages/spoke-connect-ts/tests/fixtures/golden-hello.json",
      "crates/spoke-connect/bindings/csharp/Smoke/fixtures/golden-hello.json",
      "crates/spoke-connect/bindings/kotlin/Smoke/fixtures/golden-hello.json",
      "crates/spoke-connect/bindings/swift/Smoke/fixtures/golden-hello.json",
      "crates/spoke-connect/bindings/swift/IosSmoke/Tests/IosSmokeTests/fixtures/golden-hello.json",
    ].map((p) => join(REPO_ROOT, p)),
    check: checkHelloSsot,
    // --write refresh: rewrite manifest_json from `manifest` with the
    // canonical serde field order (the only derived field in the SSOT).
    refreshSsot: (ssot) => {
      const canonical = JSON.parse(JSON.stringify(ssot));
      canonical.manifest_json = canonicalManifestJson(canonical.manifest);
      return JSON.stringify(canonical, null, 2) + "\n";
    },
  },
  {
    name: "envelope-auth",
    ssotPath: join(REPO_ROOT, "crates/spoke-connect/tests/fixtures/golden-envelope-auth.json"),
    // TS consumer (Rust reads the SSOT directly via include_str!).
    copies: [
      "packages/spoke-connect-ts/tests/fixtures/golden-envelope-auth.json",
    ].map((p) => join(REPO_ROOT, p)),
    check: checkEnvelopeAuthSsot,
    // No derived fields — every value is pinned; --write only refreshes copies.
    refreshSsot: null,
  },
];

function verify() {
  const problems = [];
  const vectors = [];
  for (const vector of VECTORS) {
    let ssotText;
    try {
      ssotText = readFileSync(vector.ssotPath, "utf8");
    } catch (e) {
      problems.push(`${vector.name} SSOT ${vector.ssotPath}: unreadable (${e.message})`);
      continue;
    }
    let ssot;
    try {
      ssot = JSON.parse(ssotText);
    } catch (e) {
      problems.push(`${vector.name} SSOT ${vector.ssotPath}: not valid JSON: ${e.message}`);
      continue;
    }
    // Structural problems are prefixed with the vector name so --write can
    // attribute them; copy-drift problems are pushed below without the
    // prefix (they are exactly what --write refreshes).
    const before = problems.length;
    vector.check(ssot, problems);
    for (let i = before; i < problems.length; i++) {
      problems[i] = `${vector.name}: ${problems[i]}`;
    }

    for (const copy of vector.copies) {
      let copyText;
      try {
        copyText = readFileSync(copy, "utf8");
      } catch (e) {
        problems.push(`${vector.name} registered copy ${copy}: unreadable (${e.message})`);
        continue;
      }
      if (copyText !== ssotText) {
        problems.push(`${vector.name} registered copy ${copy}: differs from SSOT (run with --write to refresh)`);
      }
    }
    vectors.push({ ...vector, ssot, ssotText });
  }
  return { problems, vectors };
}

/** Problems that --write must NOT paper over (SSOT structural issues). */
function structuralProblems(problems, name) {
  return problems.filter(
    (p) => p.startsWith(`${name}: `) || p.startsWith(`${name} SSOT `),
  );
}

function writeCopies(vectors) {
  for (const vector of vectors) {
    for (const copy of vector.copies) {
      writeFileSync(copy, vector.ssotText);
      console.log(`refreshed ${join(".", copy)}`);
    }
  }
}

function main() {
  const { problems, vectors } = verify();

  if (writeMode) {
    for (const vector of vectors) {
      // Structural problems in a SSOT itself block --write for that vector;
      // copy drift problems are exactly what --write refreshes.
      const structural = structuralProblems(problems, vector.name);
      if (structural.length > 0) {
        for (const p of structural) console.error(`FAIL  ${p}`);
        console.error(`golden-vector-sync: --write aborted for ${vector.name} (SSOT structural problems)`);
        process.exit(1);
      }
    }
    for (const vector of vectors) {
      if (vector.refreshSsot) {
        const refreshed = vector.refreshSsot(vector.ssot);
        if (refreshed !== vector.ssotText) {
          writeFileSync(vector.ssotPath, refreshed);
          console.log(`refreshed ${join(".", vector.ssotPath)} (derived fields)`);
          vector.ssotText = refreshed;
        }
      }
    }
    writeCopies(vectors);
    // Re-verify after refresh.
    const after = verify();
    for (const p of after.problems) console.error(`FAIL  ${p}`);
    if (after.problems.length > 0) {
      console.error("golden-vector-sync: --write left drift behind");
      process.exit(1);
    }
    console.log("golden-vector-sync: all copies byte-identical to their SSOTs");
    process.exit(0);
  }

  for (const p of problems) console.error(`FAIL  ${p}`);
  if (problems.length > 0) {
    console.error(
      `golden-vector-sync: ${problems.length} problem(s) — refresh with --write or fix the SSOT`,
    );
    process.exit(1);
  }
  const copies = vectors.reduce((n, v) => n + v.copies.length, 0);
  console.log(`golden-vector-sync: ${vectors.length} SSOTs + ${copies} registered copies byte-identical`);
  process.exit(0);
}

main();
