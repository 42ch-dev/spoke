#!/usr/bin/env node
// Build `docs/public/llms-full.txt` — one Markdown bundle of every English
// docs page, in reading order, for agent consumption.
//
// Source of truth stays the page files; this script only concatenates them and
// rewrites site-absolute links to absolute URLs. Run before `vitepress build`
// so the bundle lands in the public directory.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const DOCS = join(REPO_ROOT, "docs");
const SITE = "https://spoke.42ch.dev";

// Reference first: field facts an agent should read before procedures.
const ORDER = [
  "index.md",
  "agents.md",
  "reference/protocol.md",
  "reference/data-model.md",
  "reference/mind-state.md",
  "reference/ops.md",
  "reference/memory.md",
  "reference/connect.md",
  "explanation/concepts.md",
  "explanation/connect.md",
  "explanation/domain-profiles.md",
  "how-to/implement-adapter.md",
  "how-to/orchestrate-ops.md",
  "how-to/connect-ts-client.md",
  "how-to/connect-remote-adapter.md",
  "how-to/connect-remote-tools.md",
  "how-to/multi-peer-routing.md",
  "how-to/connect-native-bindings.md",
  "how-to/connect-cpp-binding.md",
  "how-to/remote-adapter-native-binding.md",
  "how-to/walk-toy-world.md",
  "tutorials/install-and-first-entry.md",
  "tutorials/first-connect-session.md",
  "tutorials/integrate-remote-adapter.md",
  "packages/quick-start.md",
  "release/versioning.md",
];

const stripFrontMatter = (text) => text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "");

const pagePath = (rel) => (rel === "index.md" ? "/" : `/${rel.replace(/\.md$/, "")}`);

const absolutize = (text, rel) => {
  const base = `${SITE}${pagePath(rel)}`;
  return text
    .replace(/\]\(#/g, `](${base}#`)
    .replace(/\]\(\//g, `](${SITE}/`)
    .replace(/src="\//g, `src="${SITE}/`);
};

const parts = [
  `# SPOKE full documentation

> Concatenated English docs bundle generated by tooling/docs/build-llms.mjs.
> Normative schemas live in schemas/; normative prose lives in .agents/specs/.
> Page order: reference, explanation, how-to, tutorials, packages, release.

`,
];

for (const rel of ORDER) {
  const body = stripFrontMatter(readFileSync(join(DOCS, rel), "utf8")).trim();
  parts.push(`\n<!-- page: ${rel} -->\n\n${absolutize(body, rel)}\n`);
}

const out = parts.join("");
writeFileSync(join(DOCS, "public/llms-full.txt"), out);
console.log(`llms-full.txt: ${ORDER.length} pages, ${Buffer.byteLength(out)} bytes`);
