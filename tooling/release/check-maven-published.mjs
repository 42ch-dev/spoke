#!/usr/bin/env node
/**
 * Pre-check / re-probe whether the full `dev.42ch:spoke-connect` artifact set
 * is already published on GitHub Packages Maven at the release-tag SemVer.
 *
 * Skip semantics (architect-locked): the pre-check is the PRIMARY gate. Gradle
 * has no `--skip-duplicate`, so a duplicate artifact fails `gradle publish`
 * with 409 — the pre-check is what makes a re-run at an already-published tag
 * safe, and the unconditional re-probe (`--verify`) decides green.
 *
 * Expected set (enumerated from the Gradle publication, not a hardcoded
 * guess). `build.gradle.kts` publishes `from(components["java"])` with module
 * metadata generation left at its default, so the versioned artifact set is:
 *   spoke-connect-<ver>.pom
 *   spoke-connect-<ver>.module   (Gradle Module Metadata — generated by
 *                                 default; live-confirmed 2026-08-17 by running
 *                                 `gradle publish` (9.6.1) on the real build
 *                                 files against a file:// repository)
 *   spoke-connect-<ver>.jar
 * No sources/javadoc classifiers exist (`withSourcesJar()`/`withJavadocJar()`
 * are not configured) and no native classifiers exist — the natives ride
 * INSIDE the jar as JNA classpath resources, so the probe additionally
 * asserts the downloaded jar carries the three locked JNA entries.
 *
 * Usage (from repo root):
 *   GITHUB_TOKEN=... RELEASE_TAG=v0.10.0 node tooling/release/check-maven-published.mjs
 *   GITHUB_TOKEN=... RELEASE_TAG=v0.10.0 node tooling/release/check-maven-published.mjs --verify
 *
 * Default mode emits GitHub Actions step outputs `publish_needed`
 * (`true|false`) and `missing_files` (comma-joined) to stdout and
 * `$GITHUB_OUTPUT` when set. Exit 0 for both "already published" (skip) and
 * "absent / partial" (publish needed); exit non-zero on any doubt (missing
 * GITHUB_TOKEN, network error, 401/403 auth failure, other non-404 status,
 * non-XML .pom body, non-JSON .module body, malformed jar,
 * tag/build.gradle.kts version mismatch) — fail loud, never skip on doubt.
 * Files the module metadata records beyond the expected set are logged to
 * stderr as a warning and never change the verdict (expected-set-subset
 * semantics).
 *
 * `--verify` mode (the unconditional `Confirm published set` re-probe) exits 0
 * only when the FULL expected set (pom + module + jar with all JNA entries) is
 * verified present; absent/partial or any probe error exits non-zero.
 */

import { appendFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  MAVEN_CONNECT_GRADLE_PATH,
  parseGradleVersion,
} from "./lockstep-surfaces.mjs";
import { SEMVER_PATTERN } from "./semver.mjs";

const REPO_ROOT = process.env.SPOKE_REPO_ROOT
  ? join(process.env.SPOKE_REPO_ROOT)
  : join(dirname(fileURLToPath(import.meta.url)), "../..");

/** Overridable for tests; production always probes maven.pkg.github.com. */
const MAVEN_BASE_URL =
  process.env.MAVEN_BASE_URL ?? "https://maven.pkg.github.com/42ch-dev/spoke";

/** Locked Maven coordinates of the Kotlin binding (publication in build.gradle.kts). */
const GROUP_ID = "dev.42ch";
const ARTIFACT_ID = "spoke-connect";

/**
 * Versioned files the `maven-publish` publication `from(components["java"])`
 * uploads for this project — live-confirmed by publishing the real build files
 * with Gradle 9.6.1 to a file:// repository (see header comment).
 * @type {readonly string[]}
 */
const PUBLISHED_EXTENSIONS = ["pom", "module", "jar"];

/**
 * JNA classpath resource entries the published jar must carry (mapping locked
 * by tooling/connect/assemble-kotlin-natives.sh; same RIDs as the
 * processResources block in build.gradle.kts).
 * @type {readonly string[]}
 */
const JNA_ENTRIES = [
  "linux-x86-64/libspoke_connect.so",
  "darwin-aarch64/libspoke_connect.dylib",
  "win32-x86-64/spoke_connect.dll",
];

/**
 * Expected Maven artifact filenames for a lockstep SemVer (pom + module + jar;
 * no classifiers).
 *
 * @param {string} version SemVer without the leading "v".
 * @returns {string[]}
 */
export function expectedArtifactNames(version) {
  return PUBLISHED_EXTENSIONS.map(
    (ext) => `${ARTIFACT_ID}-${version}.${ext}`,
  );
}

/**
 * Registry URL for one versioned artifact file.
 *
 * @param {string} baseUrl Registry base (default MAVEN_BASE_URL).
 * @param {string} version SemVer without the leading "v".
 * @param {string} filename Artifact filename (e.g. "spoke-connect-0.10.0.pom").
 * @returns {string}
 */
export function artifactUrl(baseUrl, version, filename) {
  const base = baseUrl.replace(/\/+$/, "");
  const groupPath = GROUP_ID.replace(/\./g, "/");
  return `${base}/${groupPath}/${ARTIFACT_ID}/${version}/${filename}`;
}

/**
 * List entry names in a ZIP archive by scanning the End Of Central Directory
 * record and the central directory. Reads only metadata — no decompression.
 *
 * Standard (non-zip64) archives only; Gradle jar tasks and CI-produced jars
 * are regular zips. Anything else fails loudly (never a silent skip).
 *
 * @param {Buffer} buffer
 * @returns {string[]}
 */
export function listZipEntryNames(buffer) {
  if (buffer.length < 22) {
    throw new Error("not a ZIP archive (too small for an End Of Central Directory record)");
  }
  // The EOCD record (minimum 22 bytes) is the last structure before an
  // optional comment of up to 65535 bytes — scan backwards from the end.
  let eocd = -1;
  const scanStart = Math.max(0, buffer.length - 22 - 65535);
  for (let i = buffer.length - 22; i >= scanStart; i -= 1) {
    if (buffer.readUInt32LE(i) === 0x06054b50) {
      eocd = i;
      break;
    }
  }
  if (eocd === -1) {
    throw new Error("not a ZIP archive (no End Of Central Directory record)");
  }
  const entryCount = buffer.readUInt16LE(eocd + 10);
  const cdSize = buffer.readUInt32LE(eocd + 12);
  const cdOffset = buffer.readUInt32LE(eocd + 16);
  if (cdOffset + cdSize > buffer.length) {
    throw new Error("not a ZIP archive (central directory out of bounds)");
  }

  const names = [];
  let offset = cdOffset;
  for (let i = 0; i < entryCount; i += 1) {
    if (offset + 46 > buffer.length) {
      throw new Error("not a ZIP archive (truncated central directory)");
    }
    if (buffer.readUInt32LE(offset) !== 0x02014b50) {
      throw new Error("not a ZIP archive (invalid central directory entry)");
    }
    const nameLen = buffer.readUInt16LE(offset + 28);
    const extraLen = buffer.readUInt16LE(offset + 30);
    const commentLen = buffer.readUInt16LE(offset + 32);
    const nameStart = offset + 46;
    names.push(buffer.toString("utf8", nameStart, nameStart + nameLen));
    offset = nameStart + nameLen + extraLen + commentLen;
  }
  return names;
}

/**
 * Probe GitHub Packages Maven for the full expected set at a version.
 *
 * @param {object} opts
 * @param {string} opts.version SemVer without the leading "v".
 * @param {string} opts.token GITHUB_TOKEN (Bearer auth; must read the package).
 * @param {string} [opts.baseUrl] Override for tests; defaults to the live registry.
 * @returns {Promise<{ outcome: "published" | "absent" | "partial"; missingFiles: string[]; unexpectedEntries: string[] }>}
 *   `unexpectedEntries` lists files the module metadata records beyond the
 *   expected set (observability only — subset semantics, the verdict never
 *   depends on it).
 * @throws {Error} Fail-loud conditions (network, auth 401/403, other
 *   non-404 status, non-XML .pom body, non-JSON .module body, malformed jar
 *   payload).
 */
async function probeMaven({ version, token, baseUrl = MAVEN_BASE_URL }) {
  const filenames = expectedArtifactNames(version);
  const expectedNames = new Set(filenames);
  /** @type {Record<string, "present" | "absent">} */
  const presence = {};
  /** @type {Buffer | null} */
  let jarBuffer = null;
  /** @type {Set<string>} Files the module metadata lists beyond the expected set. */
  const unexpectedEntries = new Set();

  for (const filename of filenames) {
    const url = artifactUrl(baseUrl, version, filename);
    let response;
    try {
      response = await fetch(url, {
        headers: { Authorization: `Bearer ${token}` },
        signal: AbortSignal.timeout(30_000),
      });
    } catch (err) {
      throw new Error(`cannot reach GitHub Packages Maven at ${url}: ${err.message}`);
    }
    if (response.status === 404) {
      presence[filename] = "absent";
      continue;
    }
    if (response.status === 401 || response.status === 403) {
      throw new Error(
        `GitHub Packages Maven authentication failed (HTTP ${response.status}) for ${url} — GITHUB_TOKEN needs read:packages scope`,
      );
    }
    if (!response.ok) {
      throw new Error(
        `GitHub Packages Maven returned HTTP ${response.status} for ${url}`,
      );
    }
    if (filename.endsWith(".pom")) {
      const text = await response.text();
      if (!text.trimStart().startsWith("<?xml")) {
        throw new Error(
          `GitHub Packages Maven served a non-XML body for ${url} (expected .pom content)`,
        );
      }
    } else if (filename.endsWith(".module")) {
      const text = await response.text();
      if (!text.trimStart().startsWith("{")) {
        throw new Error(
          `GitHub Packages Maven served a non-JSON body for ${url} (expected .module content)`,
        );
      }
      // The module metadata records the publication's file list — surface any
      // entry outside the expected set (observability only, subset semantics).
      let metadata;
      try {
        metadata = JSON.parse(text);
      } catch (err) {
        throw new Error(
          `GitHub Packages Maven module metadata is not valid JSON for ${url}: ${err.message}`,
        );
      }
      if (Array.isArray(metadata?.files)) {
        for (const entry of metadata.files) {
          if (typeof entry?.name === "string" && !expectedNames.has(entry.name)) {
            unexpectedEntries.add(entry.name);
          }
        }
      }
    } else if (filename.endsWith(".jar")) {
      jarBuffer = Buffer.from(await response.arrayBuffer());
    }
    presence[filename] = "present";
  }

  const unexpected = [...unexpectedEntries];
  const missingFiles = filenames.filter(
    (filename) => presence[filename] !== "present",
  );

  if (jarBuffer) {
    let entries;
    try {
      entries = new Set(listZipEntryNames(jarBuffer));
    } catch (err) {
      throw new Error(
        `GitHub Packages Maven jar ${ARTIFACT_ID}-${version}.jar is not a valid archive: ${err.message}`,
      );
    }
    for (const entry of JNA_ENTRIES) {
      if (!entries.has(entry)) {
        missingFiles.push(entry);
      }
    }
  }

  if (missingFiles.length === 0) {
    return { outcome: "published", missingFiles: [], unexpectedEntries: unexpected };
  }
  const allAbsent =
    filenames.every((filename) => presence[filename] === "absent") &&
    !jarBuffer;
  return {
    outcome: allAbsent ? "absent" : "partial",
    missingFiles,
    unexpectedEntries: unexpected,
  };
}

async function main() {
  const verify = process.argv.includes("--verify");

  const releaseTag = process.env.RELEASE_TAG?.trim();
  if (!releaseTag) {
    console.error(
      "check-maven-published: RELEASE_TAG env var is required (e.g. v0.10.0 or v0.10.0-rc.1)",
    );
    process.exit(1);
  }
  if (!releaseTag.startsWith("v")) {
    console.error(
      `check-maven-published: RELEASE_TAG must start with "v" (got "${releaseTag}")`,
    );
    process.exit(1);
  }
  const version = releaseTag.slice(1);
  if (!SEMVER_PATTERN.test(version)) {
    console.error(
      `check-maven-published: RELEASE_TAG SemVer segment invalid (got "${version}")`,
    );
    process.exit(1);
  }

  const token = process.env.GITHUB_TOKEN?.trim();
  if (!token) {
    console.error(
      "check-maven-published: GITHUB_TOKEN env var is required (GitHub Packages Maven probe)",
    );
    process.exit(1);
  }

  // The registry path is derived from the tag; cross-check it against the
  // lockstep version surface so a mismatched tag never probes a wrong version.
  let gradleVersion;
  try {
    const contents = readFileSync(
      join(REPO_ROOT, MAVEN_CONNECT_GRADLE_PATH),
      "utf8",
    );
    gradleVersion = parseGradleVersion(contents);
    if (!gradleVersion) {
      throw new Error(`missing version = "…"`);
    }
  } catch (err) {
    console.error(
      `check-maven-published: cannot read version from ${MAVEN_CONNECT_GRADLE_PATH}: ${err.message}`,
    );
    process.exit(1);
  }
  if (gradleVersion !== version) {
    console.error(
      `check-maven-published: ${MAVEN_CONNECT_GRADLE_PATH} version "${gradleVersion}" does not match RELEASE_TAG version "${version}"`,
    );
    process.exit(1);
  }

  let outcome;
  try {
    outcome = await probeMaven({ version, token });
  } catch (err) {
    console.error(`check-maven-published: ${err.message}`);
    process.exit(1);
  }

  if (outcome.unexpectedEntries.length > 0) {
    console.error(
      `check-maven-published: warning — module metadata lists files outside the expected set for ${GROUP_ID}:${ARTIFACT_ID} ${version}: ${outcome.unexpectedEntries.join(", ")}`,
    );
  }

  const expected = expectedArtifactNames(version);
  const missing = outcome.missingFiles.join(",");

  if (outcome.outcome === "published") {
    console.log(
      `check-maven-published: ${GROUP_ID}:${ARTIFACT_ID} ${version} already published on GitHub Packages Maven (${expected.length}/${expected.length} expected files present, JNA natives verified) — skip publish`,
    );
  } else if (outcome.outcome === "absent") {
    console.log(
      `check-maven-published: ${GROUP_ID}:${ARTIFACT_ID} ${version} not found on GitHub Packages Maven (HTTP 404) — publish needed`,
    );
  } else {
    console.log(
      `check-maven-published: ${GROUP_ID}:${ARTIFACT_ID} ${version} partially published on GitHub Packages Maven — publish needed; missing: ${missing}`,
    );
  }

  if (verify) {
    if (outcome.outcome !== "published") {
      console.error(
        `check-maven-published: verify failed — expected files missing from GitHub Packages Maven: ${missing}`,
      );
      process.exit(1);
    }
    console.log("check-maven-published: confirmed full expected set on GitHub Packages Maven");
    process.exit(0);
  }

  const publishNeeded = outcome.outcome !== "published";
  console.log(`publish_needed=${publishNeeded}`);
  console.log(`missing_files=${missing}`);
  const githubOutput = process.env.GITHUB_OUTPUT;
  if (githubOutput) {
    appendFileSync(githubOutput, `publish_needed=${publishNeeded}\n`);
    appendFileSync(githubOutput, `missing_files=${missing}\n`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
